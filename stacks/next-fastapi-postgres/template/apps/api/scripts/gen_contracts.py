"""Generates packages/shared/src/generated.ts (zod schemas + types) from the Pydantic contracts.

    uv run --project apps/api python apps/api/scripts/gen_contracts.py           write the file
    uv run --project apps/api python apps/api/scripts/gen_contracts.py --check   exit 1 if it is out of date

The Pydantic models in apps/api/app/contracts are the single source of truth; the web app imports the
generated schemas from @app/shared and never defines an API shape itself. Supports the JSON Schema that
contracts use (strings with lengths, formats and messages, numbers, booleans, enums, literals, lists,
dicts, optional and nullable fields, nested models); anything else stops the generator with an error.
"""

import json
import re
import sys
from enum import Enum
from pathlib import Path
from typing import Any

API_DIR = Path(__file__).resolve().parents[1]
OUT = API_DIR.parents[1] / "packages" / "shared" / "src" / "generated.ts"
sys.path.insert(0, str(API_DIR))

from pydantic import BaseModel  # noqa: E402
from pydantic.json_schema import models_json_schema  # noqa: E402

from app import contracts  # noqa: E402

HEADER = (
    "// Generated by apps/api/scripts/gen_contracts.py from apps/api/app/contracts. Do not edit:\n"
    "// change the Pydantic model and run the generator (./verify --quick says when this file is stale).\n"
    "import { z } from 'zod';"
)


class Unsupported(Exception):
    pass


def ts(value: Any) -> str:
    """A TypeScript literal in single quotes (eslint's quote rule)."""
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return json.dumps(value)


def lower_first(name: str) -> str:
    return name[:1].lower() + name[1:]


def schema_name(model: str) -> str:
    return lower_first(model) + "Schema"


def string_expr(s: dict[str, Any]) -> str:
    messages = s.get("x-messages", {})
    transforms = "".join({"trim": ".trim()", "lower": ".toLowerCase()"}[t] for t in s.get("x-transform", []))
    fmt = s.get("format")
    if fmt == "email":
        inner = f"z.email({ts(messages['format'])})" if "format" in messages else "z.email()"
        if "maxLength" in s:
            inner += f".max({s['maxLength']})"
        return f"z.string(){transforms}.pipe({inner})" if transforms else inner
    if fmt == "uuid":
        return "z.uuid()"
    if fmt == "date-time":
        return "z.iso.datetime({ offset: true })"
    if fmt == "date":
        return "z.iso.date()"
    if fmt not in (None, "password"):
        raise Unsupported(f"string format {fmt!r}")
    out = "z.string()" + transforms
    if "minLength" in s:
        msg = f", {ts(messages['min'])}" if "min" in messages else ""
        out += f".min({s['minLength']}{msg})"
    if "maxLength" in s:
        msg = f", {ts(messages['max'])}" if "max" in messages else ""
        out += f".max({s['maxLength']}{msg})"
    if "pattern" in s:
        out += f".regex(new RegExp({ts(s['pattern'])}))"
    return out


def expr(s: dict[str, Any]) -> str:  # noqa: PLR0911, PLR0912 - one branch per JSON Schema kind
    if "$ref" in s:
        return schema_name(s["$ref"].rsplit("/", 1)[1])
    if "const" in s:
        return f"z.literal({ts(s['const'])})"
    if "enum" in s:
        return "z.enum([" + ", ".join(ts(v) for v in s["enum"]) + "])"
    for key in ("anyOf", "oneOf"):
        if key in s:
            options = [o for o in s[key] if o.get("type") != "null"]
            nullable = len(options) < len(s[key])
            inner = expr(options[0]) if len(options) == 1 else "z.union([" + ", ".join(expr(o) for o in options) + "])"
            return inner + (".nullable()" if nullable else "")
    kind = s.get("type")
    if kind == "string":
        return string_expr(s)
    if kind in ("integer", "number"):
        out = "z.number()" + (".int()" if kind == "integer" else "")
        for key, method in (
            ("minimum", "min"),
            ("maximum", "max"),
            ("exclusiveMinimum", "gt"),
            ("exclusiveMaximum", "lt"),
        ):
            if key in s:
                out += f".{method}({s[key]})"
        return out
    if kind == "boolean":
        return "z.boolean()"
    if kind == "null":
        return "z.null()"
    if kind == "array":
        out = f"z.array({expr(s.get('items', {}))})"
        if "minItems" in s:
            out += f".min({s['minItems']})"
        if "maxItems" in s:
            out += f".max({s['maxItems']})"
        return out
    if kind == "object":
        if "properties" in s:
            return object_expr(s, "  ")
        extra = s.get("additionalProperties")
        if isinstance(extra, dict):
            return f"z.record(z.string(), {expr(extra)})"
    raise Unsupported(f"schema {json.dumps(s)[:120]}")


def object_expr(s: dict[str, Any], indent: str = "") -> str:
    required = set(s.get("required", []))
    lines = []
    for name, prop in s["properties"].items():
        value = expr(prop) + ("" if name in required else ".optional()")
        key = name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else ts(name)
        lines.append(f"{indent}  {key}: {value},")
    return "z.object({\n" + "\n".join(lines) + f"\n{indent}}})"


def refs(s: Any) -> set[str]:
    if isinstance(s, dict):
        found = {s["$ref"].rsplit("/", 1)[1]} if "$ref" in s else set()
        for v in s.values():
            found |= refs(v)
        return found
    if isinstance(s, list):
        return set().union(*(refs(v) for v in s)) if s else set()
    return set()


def generate() -> str:
    exported = [getattr(contracts, n) for n in contracts.__all__]
    models = [m for m in exported if isinstance(m, type) and issubclass(m, BaseModel) and m is not contracts.Contract]
    enums = [e for e in exported if isinstance(e, type) and issubclass(e, Enum)]
    _, top = models_json_schema([(m, "validation") for m in models], by_alias=True, ref_template="#/$defs/{model}")
    defs: dict[str, Any] = top.get("$defs", {})
    out = [HEADER]
    for enum in enums:
        name = enum.__name__
        out.append(f"\n/** {(enum.__doc__ or '').strip()} */\nexport const {name} = {{")
        for member in enum:
            key = "".join(part.capitalize() for part in member.name.split("_"))
            out.append(f"  {key}: {ts(member.value)},")
        out.append(f"}} as const;\nexport type {name} = (typeof {name})[keyof typeof {name}];")
    done: set[str] = set()

    def emit(name: str, stack: tuple[str, ...] = ()) -> None:
        if name in done:
            return
        if name in stack:
            raise Unsupported(f"recursive model {name}")
        for dep in sorted(refs(defs[name]) - {name}):
            emit(dep, (*stack, name))
        doc = defs[name].get("description")
        out.append("")
        if doc:
            out.append("/** " + " ".join(doc.split()) + " */")
        out.append(f"export const {schema_name(name)} = {object_expr(defs[name])};")
        out.append(f"export type {name} = z.infer<typeof {schema_name(name)}>;")
        done.add(name)

    for name in sorted(defs):
        emit(name)
    return "\n".join(out) + "\n"


def main() -> int:
    try:
        text = generate()
    except Unsupported as err:
        print(f"gen_contracts: unsupported contract shape: {err}", file=sys.stderr)
        return 1
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(
                f"{OUT.relative_to(API_DIR.parents[1])} is out of date with apps/api/app/contracts: run "
                "`uv run --project apps/api python apps/api/scripts/gen_contracts.py` and commit the result",
                file=sys.stderr,
            )
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(API_DIR.parents[1])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
